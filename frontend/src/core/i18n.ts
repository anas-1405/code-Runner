let current: Lang = (localStorage.getItem('lang') as Lang) || 'ar';

export function t(key: string): string {
  return dict[current][key] || key;
}

export function getLang(): Lang {
  return current;
}

export function setLang(l: string): void {
  if (['ar', 'en', 'tr', 'fr', 'de', 'es', 'nl', 'it'].includes(l)) {
    current = l as Lang;
    localStorage.setItem('lang', l);
  }
}
